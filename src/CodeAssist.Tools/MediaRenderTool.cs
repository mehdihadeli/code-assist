using System.Security.Cryptography;
using System.Text.Json;
using CodeAssist.Tools.Text;
using CodeAssist.Tools;
using CodeAssist.Workspaces.Platform;
using CodeAssist.Contracts;

namespace CodeAssist.Tools;

public sealed class MediaRenderTool(IImageRenderer renderer, IToolJobs jobs, IFileSystem fileSystem) : ITool
{
    public ToolSpec Spec => new("media.render", "Generate or edit an image as a background job. Reference paths must be supported images. Optional destination is created atomically; overwriting requires expectHash. Read the job result for generated bytes, hash and saved path. Models: " + string.Join(", ", renderer.Models.Select(model => model.Reference)),
        """
        {"type":"object","properties":{"prompt":{"type":"string"},"model":{"type":"string"},
         "references":{"type":"array","maxItems":8,"items":{"type":"object","properties":{"path":{"type":"string"}},"required":["path"]}},
         "path":{"type":"string"},"expectHash":{"type":"string"}},"required":["prompt"],"additionalProperties":false}
        """, ToolRisk.Network, ["media", "net", "write"]);

    private sealed record Request(string Prompt, string Model, IReadOnlyList<ResolvedPath> References, ResolvedPath? Destination, string? Hash);

    public ValueTask<ToolPlan> PlanAsync(ToolArguments arguments, ToolContext context, CancellationToken cancellationToken)
    {
        var request = Parse(arguments, context);
        var effects = new List<ToolEffect> { new(ToolEffectKind.Net, $"image:{request.Model}") };
        effects.AddRange(request.References.Select(path => ToolSupport.Effect(ToolEffectKind.Read, path)));
        if (request.Destination is { } destination) effects.Add(ToolSupport.Effect(ToolEffectKind.Write, destination));
        return new(new ToolPlan(effects, $"Render image with {request.Model}; save to {request.Destination?.Full ?? "job result"}."));
    }

    public Task<ToolResult> ExecuteAsync(ToolArguments arguments, ToolContext context, CancellationToken cancellationToken)
    {
        var request = Parse(arguments, context);
        return ToolSupport.FromPortAsync(async () =>
        {
            var references = new List<ToolAttachment>();
            long total = 0;
            foreach (var path in request.References)
            {
                var facts = fileSystem.Stat(path.Full);
                if (facts is null || facts.IsDirectory || facts.Length > context.Limits.MaxAttachmentBytes) return ToolResult.Error("Reference image missing or over byte limit.");
                var bytes = await fileSystem.ReadAllBytesAsync(path.Full, cancellationToken);
                total += bytes.Length;
                var mime = ContentSniffer.AttachmentMime(bytes.AsSpan(0, Math.Min(bytes.Length, ContentSniffer.HeadBytes)));
                if (mime is null || !mime.StartsWith("image/", StringComparison.Ordinal) || total > context.Limits.MaxAttachmentBytes) return ToolResult.Error("References must be images within aggregate byte budget.");
                references.Add(new(mime, bytes));
            }
            var original = await DestinationHashAsync(request, cancellationToken);
            var job = jobs.Start($"Render image: {request.Model}", async token =>
            {
                var image = await renderer.RenderAsync(new(request.Model, request.Prompt, references), token);
                var mime = ContentSniffer.AttachmentMime(image.Data.AsSpan(0, Math.Min(image.Data.Length, ContentSniffer.HeadBytes)));
                if (mime is null || !mime.StartsWith("image/", StringComparison.Ordinal) || image.Data.Length > context.Limits.MaxAttachmentBytes)
                    return ToolResult.Error("Generated output is not a supported image or exceeds the media budget.");
                token.ThrowIfCancellationRequested();
                if (request.Destination is { } destination)
                {
                    var current = fileSystem.Stat(destination.Full);
                    if ((original is null && current is not null) || (original is not null && (current is null ||
                        !string.Equals(TextFiles.Hash(await fileSystem.ReadAllBytesAsync(destination.Full, token)), original, StringComparison.Ordinal))))
                        return ToolResult.Error("Destination changed during image generation; refusing overwrite.");
                    await fileSystem.WriteAtomicAsync(destination.Full, image.Data, token);
                }
                return new ToolResult(JsonSerializer.Serialize(new { model = request.Model, mimeType = mime, sha256 = TextFiles.Hash(image.Data), bytes = image.Data.Length, path = request.Destination?.Full }),
                    Attachments: [new(mime, image.Data)]);
            }, context, cancellationToken);
            return ToolResult.Ok($"Image job: {job.Id}. Completion is reported by host; read final media through job.read.");
        }, cancellationToken);
    }

    private async Task<string?> DestinationHashAsync(Request request, CancellationToken cancellationToken)
    {
        if (request.Destination is not { } destination || fileSystem.Stat(destination.Full) is null) return null;
        if (request.Hash is null) throw new IOException("Destination exists; supply its expectHash to overwrite.");
        var hash = TextFiles.Hash(await fileSystem.ReadAllBytesAsync(destination.Full, cancellationToken));
        if (!string.Equals(hash, request.Hash, StringComparison.OrdinalIgnoreCase)) throw new IOException("Destination hash does not match; refusing overwrite.");
        return hash;
    }

    private Request Parse(ToolArguments arguments, ToolContext context)
    {
        var prompt = arguments.RequireString("prompt");
        var model = arguments.String("model") ?? renderer.Models.FirstOrDefault()?.Reference ?? "";
        var paths = arguments.Objects("references").Select(item => item.RequireString("path")).ToArray();
        var path = arguments.String("path");
        var hash = arguments.String("expectHash");
        var capability = renderer.Models.FirstOrDefault(item => item.Reference == model);
        if (string.IsNullOrWhiteSpace(prompt) || prompt.Length > 32000) arguments.Issue("Prompt must contain 1-32000 characters.");
        if (capability is null || paths.Length > capability.MaxReferences || paths.Length > 8 || (paths.Length > 0 && !capability.CanEdit)) arguments.Issue("Image model unavailable or does not support requested reference count.");
        if (hash is not null && (hash.Length != 64 || !hash.All(Uri.IsHexDigit) || path is null)) arguments.Issue("expectHash requires destination and SHA-256 hex value.");
        arguments.Validate();
        return new(prompt, model, paths.Select(value => ToolSupport.Resolve(value, context)).ToArray(), path is null ? null : ToolSupport.Resolve(path, context), hash);
    }
}